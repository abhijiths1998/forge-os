# Glass: the alpha values above make backgrounds translucent. Darkly (the
# widget style) turns any window whose Window colour has alpha into a
# translucent one, and KWin's Glass effect frosts whatever shows through.
# Views (file lists, text editors) stay the most opaque so text reads well.


def rgb(h, alpha=255):
    h = h.lstrip("#")
    out = ",".join(str(int(h[i:i + 2], 16)) for i in (0, 2, 4))
    return out if alpha == 255 else f"{out},{alpha}"


def section(name, p, bg, fg=None, alpha=255):
    fg = fg or p["window_fg"]
    return f"""[Colors:{name}]
BackgroundAlternate={rgb(bg[1], alpha)}
BackgroundNormal={rgb(bg[0], alpha)}
DecorationFocus={rgb(p['focus'])}
DecorationHover={rgb(p['hover'])}
ForegroundActive={rgb(p['focus'])}
ForegroundInactive={rgb(p['inactive_fg'])}
ForegroundLink={rgb(p['link'])}
ForegroundNegative={rgb(p['negative'])}
ForegroundNeutral={rgb(p['neutral'])}
ForegroundNormal={rgb(fg)}
ForegroundPositive={rgb(p['positive'])}
ForegroundVisited={rgb(p['visited'])}

"""


def kde_scheme(p, ident):
    out = """# Generated by branding-source/glass/colors.py; edit there.
[ColorEffects:Disabled]
Color=56,56,56
ColorAmount=0
ColorEffect=0
ContrastAmount=0.65
ContrastEffect=1
IntensityAmount=0.1
IntensityEffect=2

[ColorEffects:Inactive]
ChangeSelectionColor=true
Color=112,111,110
ColorAmount=0.025
ColorEffect=2
ContrastAmount=0.1
ContrastEffect=2
Enable=false
IntensityAmount=0
IntensityEffect=0

"""
    out += section("Button", p, p["button"])
    out += section("Complementary", p, p["complementary"], p["complementary_fg"])
    a = p["alpha"]
    out += section("Header", p, p["header"], alpha=a["header"])
    out += section("Header][Inactive", p, p["window"], alpha=a["window"])
    sel = dict(p, window_fg=p["selection_fg"])
    out += section("Selection", sel, (p["selection"], p["selection"]), p["selection_fg"])
    out += section("Tooltip", p, (p["tooltip"], p["window"][0]), alpha=a["tooltip"])
    out += section("View", p, p["view"], alpha=a["view"])
    out += section("Window", p, p["window"], alpha=a["window"])
    out += f"""[General]
ColorScheme={ident}
Name={p['name']}
shadeSortColumn=true

[KDE]
contrast=4

[WM]
activeBackground={rgb(p['wm_active'][0], a['titlebar'])}
activeBlend={rgb(p['wm_active'][1])}
activeForeground={rgb(p['wm_active'][1])}
inactiveBackground={rgb(p['wm_inactive'][0], a['titlebar'])}
inactiveBlend={rgb(p['wm_inactive'][1])}
inactiveForeground={rgb(p['wm_inactive'][1])}
"""
    return out


# Terminal: the same dark navy glass in both light and dark mode, as in the
# rest of the design: terminals read better dark, and the panel is translucent.
KONSOLE = {
    "Background": "#232640", "Foreground": "#E4E6F4",
    "Color0": "#2E3254", "Color1": "#F28B9B", "Color2": "#8FD3A8", "Color3": "#F6CFA8",
    "Color4": "#8A9BF7", "Color5": "#C3B7EE", "Color6": "#9DBEF0", "Color7": "#D8DBEE",
    "Color0Intense": "#5A5F86", "Color1Intense": "#F7A9B6", "Color2Intense": "#A9E2BF",
    "Color3Intense": "#F9DDBF", "Color4Intense": "#A3B0FA", "Color5Intense": "#D6CDF5",
    "Color6Intense": "#B9D2F5", "Color7Intense": "#FFFFFF",
}


def konsole_scheme():
    out = "# Generated by branding-source/glass/colors.py; edit there.\n"
    for key, val in KONSOLE.items():
        out += f"[{key}]\nColor={rgb(val)}\n\n"
        base = key.replace("Intense", "")
        if key in ("Background", "Foreground"):
            out += f"[{key}Intense]\nColor={rgb(val)}\n\n[{key}Faint]\nColor={rgb(val)}\n\n"
        elif not key.endswith("Intense"):
            out += f"[{base}Faint]\nColor={rgb(val)}\n\n"
    out += "[General]\nBlur=true\nColorRandomization=false\nDescription=Forge Glass\nOpacity=0.72\nWallpaper=\n"
    return out


def main():
    cs = ROOT / "color-schemes"
    cs.mkdir(parents=True, exist_ok=True)
    (cs / "ForgeGlassLight.colors").write_text(kde_scheme(LIGHT, "ForgeGlassLight"))
    (cs / "ForgeGlassDark.colors").write_text(kde_scheme(DARK, "ForgeGlassDark"))
    ko = ROOT / "konsole"
    ko.mkdir(parents=True, exist_ok=True)
    (ko / "ForgeGlass.colorscheme").write_text(konsole_scheme())
    print("wrote colour schemes")


if __name__ == "__main__":
    main()

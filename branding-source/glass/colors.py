"""Write the Forge Glass KDE colour schemes and Konsole scheme.

    python3 branding-source/glass/colors.py

One palette, three outputs, straight into profile/airootfs, so the
desktop, the terminal and the wallpaper (generate.py) never drift apart.
"""

// KDE colour scheme and Konsole colour scheme files for a ForgeTheme: the
// same format branding-source/glass/colors.py writes for Forge Glass.
import 'dart:ui';

import 'palette.dart';
import 'theme.dart';

String _rgb(Color c, [int alpha = 255]) {
  final v = c.toARGB32();
  final rgb = '${(v >> 16) & 0xFF},${(v >> 8) & 0xFF},${v & 0xFF}';
  return alpha == 255 ? rgb : '$rgb,$alpha';
}

String kdeColourScheme(ForgeTheme theme, {required String ident}) {
  final c = ThemeColours(theme);
  final b = c.base;
  String section(String name, (Color, Color) bg,
      {Color? fg, int alpha = 255, Color? normal}) {
    return '''[Colors:$name]
BackgroundAlternate=${_rgb(bg.$2, alpha)}
BackgroundNormal=${_rgb(bg.$1, alpha)}
DecorationFocus=${_rgb(c.focus)}
DecorationHover=${_rgb(c.hover)}
ForegroundActive=${_rgb(c.focus)}
ForegroundInactive=${_rgb(c.tint(b.inactiveFg))}
ForegroundLink=${_rgb(c.link)}
ForegroundNegative=${_rgb(b.negative)}
ForegroundNeutral=${_rgb(b.neutral)}
ForegroundNormal=${_rgb(normal ?? fg ?? b.windowFg)}
ForegroundPositive=${_rgb(b.positive)}
ForegroundVisited=${_rgb(c.visited)}

''';
  }

  final window = c.tint2(b.window);
  final out = StringBuffer('''# Generated by Forge Theming Kit (${theme.name}).
[ColorEffects:Disabled]
Color=56,56,56
ColorAmount=0
ColorEffect=0
ContrastAmount=0.65
ContrastEffect=1
IntensityAmount=0.1
IntensityEffect=2

[ColorEffects:Inactive]
ChangeSelectionColor=true
Color=112,111,110
ColorAmount=0.025
ColorEffect=2
ContrastAmount=0.1
ContrastEffect=2
Enable=false
IntensityAmount=0
IntensityEffect=0

''');
  out.write(section('Button', c.tint2(b.button)));
  out.write(section('Complementary', c.tint2(b.complementary), fg: b.complementaryFg));
  out.write(section('Header', c.tint2(b.header), alpha: c.headerAlpha));
  out.write(section('Header][Inactive', window, alpha: c.windowAlpha));
  out.write(section('Selection', (c.accent, c.accent), normal: const Color(0xFFFFFFFF)));
  out.write(section('Tooltip', (c.tint(b.tooltip), window.$1), alpha: c.tooltipAlpha));
  out.write(section('View', c.tint2(b.view), alpha: c.viewAlpha));
  out.write(section('Window', window, alpha: c.windowAlpha));
  final active = c.tint(b.wmActive.$1);
  final inactive = c.tint(b.wmInactive.$1);
  out.write('''[General]
ColorScheme=$ident
Name=Forge Kit
shadeSortColumn=true

[KDE]
contrast=4

[WM]
activeBackground=${_rgb(active, c.titlebarAlpha)}
activeBlend=${_rgb(b.wmActive.$2)}
activeForeground=${_rgb(b.wmActive.$2)}
inactiveBackground=${_rgb(inactive, c.titlebarAlpha)}
inactiveBlend=${_rgb(c.tint(b.wmInactive.$2))}
inactiveForeground=${_rgb(c.tint(b.wmInactive.$2))}
''');
  return out.toString();
}

/// Konsole: colors.py's dark navy glass in both modes (terminals read
/// better dark), tinted like the rest, at the theme's terminal opacity.
String konsoleColourScheme(ForgeTheme theme) {
  final c = ThemeColours(theme);
  const colours = <String, Color>{
    'Background': Color(0xFF232640), 'Foreground': Color(0xFFE4E6F4),
    'Color0': Color(0xFF2E3254), 'Color1': Color(0xFFF28B9B),
    'Color2': Color(0xFF8FD3A8), 'Color3': Color(0xFFF6CFA8),
    'Color4': Color(0xFF8A9BF7), 'Color5': Color(0xFFC3B7EE),
    'Color6': Color(0xFF9DBEF0), 'Color7': Color(0xFFD8DBEE),
    'Color0Intense': Color(0xFF5A5F86), 'Color1Intense': Color(0xFFF7A9B6),
    'Color2Intense': Color(0xFFA9E2BF), 'Color3Intense': Color(0xFFF9DDBF),
    'Color4Intense': Color(0xFFA3B0FA), 'Color5Intense': Color(0xFFD6CDF5),
    'Color6Intense': Color(0xFFB9D2F5), 'Color7Intense': Color(0xFFFFFFFF),
  };
  final out = StringBuffer('# Generated by Forge Theming Kit (${theme.name}).\n');
  colours.forEach((key, value) {
    // Background, the black and the blue follow the tint; text and the
    // other ANSI colours stay as they are, so programs' colours still read.
    final v = (key == 'Background' || key.startsWith('Color0') || key.startsWith('Color4'))
        ? c.tint(value)
        : value;
    out.write('[$key]\nColor=${_rgb(v)}\n\n');
    if (key == 'Background' || key == 'Foreground') {
      out.write('[${key}Intense]\nColor=${_rgb(v)}\n\n[${key}Faint]\nColor=${_rgb(v)}\n\n');
    } else if (!key.endsWith('Intense')) {
      out.write('[${key}Faint]\nColor=${_rgb(v)}\n\n');
    }
  });
  out.write('[General]\nBlur=true\nColorRandomization=false\n'
      'Description=Forge Glass\nOpacity=${(theme.terminalOpacity / 100).toStringAsFixed(2)}\n'
      'Wallpaper=\n');
  return out.toString();
}
